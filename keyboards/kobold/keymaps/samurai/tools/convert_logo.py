#!/usr/bin/env python3
"""Convert an image to the 128x32 monochrome frame used by the Arasaka OLED.

Forward (image -> frame):
  python3 convert_logo.py logo.png --fit pad --dither --png logo_1bit.png --out-c logo_clean.h

Reverse (C array -> PNG), to check the bit order against oled.c:
  python3 convert_logo.py --from-c logo_clean.h --name logo_clean --png check.png

Byte layout (matches oled.c and glitch_gen.py): 512 bytes = 4 pages x 128
columns, page-major. Each byte is 8 vertical pixels, LSB = top row of the page.
"""
import argparse
import os
import re
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from glitch_gen import W, H, PAGES, FRAME_SIZE, write_c, to_display, from_display, pack_rows, unpack_rows  # noqa: E402


RESAMPLE = {
    "box": Image.BOX,          # area average: cleanest for downscaling
    "lanczos": Image.LANCZOS,  # sharper but adds ringing at small sizes
    "nearest": Image.NEAREST,
}


def autocrop(gray, threshold=128):
    """Crop to the bounding box of lit pixels so the logo fills the 128x32 frame."""
    mask = gray.point(lambda v: 255 if v >= threshold else 0)
    bbox = mask.getbbox()
    return gray.crop(bbox) if bbox else gray


def fit_image(img, mode, resample=Image.BOX, crop=False, threshold=128, size=(W, H)):
    """Return a grayscale image of `size` using the chosen fit mode."""
    tw, th = size
    if img.mode in ("RGBA", "LA") or "transparency" in img.info:
        # Composite onto black so transparent areas become unlit pixels.
        rgba = img.convert("RGBA")
        img = Image.alpha_composite(Image.new("RGBA", rgba.size, (0, 0, 0, 255)), rgba)
    img = img.convert("L")
    if crop:
        img = autocrop(img, threshold)
    if mode == "stretch":
        return img.resize((tw, th), resample)
    if mode == "pad":
        scale = min(tw / img.width, th / img.height)
        sz = (max(1, round(img.width * scale)), max(1, round(img.height * scale)))
        canvas = Image.new("L", (tw, th), 0)
        canvas.paste(img.resize(sz, resample), ((tw - sz[0]) // 2, (th - sz[1]) // 2))
        return canvas
    if mode == "cover":
        scale = max(tw / img.width, th / img.height)
        sz = (max(tw, round(img.width * scale)), max(th, round(img.height * scale)))
        big = img.resize(sz, resample)
        left = (big.width - tw) // 2
        top = (big.height - th) // 2
        return big.crop((left, top, left + tw, top + th))
    raise ValueError("unknown fit mode: " + mode)


def to_mono(gray, threshold, dither, invert):
    """Return a 1-bit image (255 = lit pixel) from a grayscale image."""
    if dither:
        # Shift brightness so that --threshold becomes the dither midpoint.
        # Lower threshold -> more pixels go white; higher -> more go black.
        shift = 128 - threshold
        shifted = gray.point(lambda v: max(0, min(255, v + shift)))
        mono = shifted.convert("1")  # Floyd-Steinberg
    else:
        mono = gray.point(lambda v: 255 if v >= threshold else 0).convert("1")
    if invert:
        mono = mono.point(lambda v: 0 if v else 255).convert("1")
    return mono


def mono_to_frame(mono):
    """Pack a 1-bit image into the 512-byte firmware frame."""
    px = mono.load()
    rows = [[1 if px[x, y] else 0 for x in range(W)] for y in range(H)]
    return pack_rows(rows)


def frame_to_mono(frame):
    """Unpack a 512-byte firmware frame into a 1-bit image (lit = white)."""
    img = Image.new("1", (W, H), 0)
    px = img.load()
    for y, row in enumerate(unpack_rows(frame)):
        for x, v in enumerate(row):
            if v:
                px[x, y] = 1
    return img


def read_c_array(path, name):
    """Read a PROGMEM char array of frame_size bytes from a C header."""
    with open(path) as fh:
        src = fh.read()
    match = re.search(r"%s\[[^\]]*\]\s*=\s*\{(.*?)\n\};" % re.escape(name), src, re.S)
    if not match:
        match = re.search(r"%s\[[^\]]*\]\s*=\s*\{(.*?)\};" % re.escape(name), src, re.S)
    if not match:
        raise SystemExit("array '%s' not found in %s" % (name, path))
    values = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", match.group(1))]
    if len(values) < FRAME_SIZE:
        raise SystemExit("array '%s' has %d bytes, expected %d" % (name, len(values), FRAME_SIZE))
    return values[:FRAME_SIZE]


def write_c_single(frame, path, name):
    lines = ["// Generated by tools/convert_logo.py -- do not edit by hand.",
             "static const char PROGMEM %s[frame_size] = {" % name]
    for row in range(0, FRAME_SIZE, 16):
        chunk = ", ".join("0x%02x" % b for b in frame[row:row + 16])
        lines.append("  " + chunk + ("," if row + 16 < FRAME_SIZE else ""))
    lines.append("};")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("image", nargs="?", help="input image (PNG/BMP/JPG...)")
    parser.add_argument("--from-c", help="read a frame from a C header instead of an image")
    parser.add_argument("--name", default="logo_clean", help="C array name (default logo_clean)")
    parser.add_argument("--fit", choices=["stretch", "pad", "cover"], default="pad",
                        help="stretch to 128x32, pad with black, or cover and center-crop")
    parser.add_argument("--threshold", type=int, default=128, help="grey cut-off: pixels darker than this go black, brighter go white (also sets the dither midpoint)")
    parser.add_argument("--dither", action="store_true", help="Floyd-Steinberg dithering instead of threshold")
    parser.add_argument("--crop", action="store_true", help="crop to the lit area before fitting (removes empty border)")
    parser.add_argument("--resample", choices=sorted(RESAMPLE), default="box",
                        help="downscale filter (default box; lanczos is sharper but noisier)")
    parser.add_argument("--invert", action="store_true", help="swap lit and unlit pixels")
    parser.add_argument("--portrait", action="store_true",
                        help="artwork and PNG output use the rotated 32x128 display (OLED_ROTATION_270)")
    parser.add_argument("--png", help="write the 1-bit 128x32 image as PNG")
    parser.add_argument("--scale", type=int, default=1, help="integer scale for the PNG (default 1)")
    parser.add_argument("--out-c", help="write the frame as a single C array")
    args = parser.parse_args()

    if args.from_c:
        frame = read_c_array(args.from_c, args.name)
        mono = frame_to_mono(frame)
        print("read %s from %s" % (args.name, args.from_c))
    else:
        if not args.image:
            parser.error("give an input image or --from-c")
        gray = Image.open(args.image)
        size = (H, W) if args.portrait else (W, H)
        gray = fit_image(gray, args.fit, RESAMPLE[args.resample], args.crop, args.threshold, size)
        gray = from_display(gray, args.portrait)
        mono = to_mono(gray, args.threshold, args.dither, args.invert)
        frame = mono_to_frame(mono)

    if args.png:
        shown = to_display(mono, args.portrait)
        out = shown if args.scale == 1 else shown.resize((shown.width * args.scale, shown.height * args.scale), Image.NEAREST)
        out.save(args.png)
        print("wrote", args.png)
    if args.out_c:
        write_c_single(frame, args.out_c, args.name)
        print("wrote", args.out_c)
    if not args.png and not args.out_c:
        print("nothing to write (use --png or --out-c)")


if __name__ == "__main__":
    main()
