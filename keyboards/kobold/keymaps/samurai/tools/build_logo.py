#!/usr/bin/env python3
"""Rebuild the OLED logo frames from tools/logo_params.json.

Every setting that shapes the logo lives in the parameter file, so a change
shows up as a diff there. Steps:
  1. convert the source image to a 1-bit 128x32 frame (convert_logo.py)
  2. generate the line-glitch pool and the dirty pool with the seeds in the file
  3. write the frames to logo_frames.h, which oled.c includes
  4. read the frames back from the header and check they match the generation
  5. render the firmware state machine as a GIF (unless --no-sim)

oled.c keeps its logic and the text frames; the logo frames live in the header.

Usage (from the keymap directory):  python3 tools/build_logo.py [--no-sim]
"""
import argparse
import json
import os
import random
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import glitch_gen as g  # noqa: E402
import simulate_firmware as s  # noqa: E402

INCLUDE_LINE = '#include "%s"'


def run(args):
    print("+", " ".join(args), flush=True)
    subprocess.run(args, cwd=ROOT, check=True)


def frame_bytes_from_header(path):
    text = open(path).read()
    return [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", text)]


def emit_array(decl, frames):
    out = [decl]
    for i, f in enumerate(frames):
        out.append("  {")
        out.append("    // frame %d" % (i + 1))
        for row in range(0, g.FRAME_SIZE, 16):
            chunk = ", ".join("0x%02x" % b for b in f[row:row + 16])
            out.append("    " + chunk + ("," if row + 16 < g.FRAME_SIZE else ""))
        out.append("  }" + ("," if i + 1 < len(frames) else ""))
    out.append("};")
    return out


def emit_single(decl, frame):
    out = [decl]
    for row in range(0, g.FRAME_SIZE, 16):
        chunk = ", ".join("0x%02x" % b for b in frame[row:row + 16])
        out.append("  " + chunk + ("," if row + 16 < g.FRAME_SIZE else ""))
    out.append("};")
    return out


def read_array(src, name):
    m = re.search(r"PROGMEM " + name + r"\[[^=]*= \{(.*?)\n\};", src, re.S)
    return [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1))]


def replace_block(lines, start, new):
    """Replace the array that begins with `start` (through its closing '};') by `new`."""
    idx = next(i for i, l in enumerate(lines) if l.startswith(start))
    end = next(i for i in range(idx, len(lines)) if lines[i] == "};")
    return lines[:idx] + new + lines[end + 1:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--params", default=os.path.join(HERE, "logo_params.json"))
    ap.add_argument("--no-sim", action="store_true", help="skip the GIF simulation")
    args = ap.parse_args()
    P = json.load(open(args.params))
    cv, gl, di, sm, arr = P["convert"], P["glitch"], P["dirty"], P["simulate"], P["arrays"]
    frames_h = os.path.join(ROOT, P["frames_h"])
    oled = os.path.join(ROOT, P["oled_c"])

    # 1. convert
    conv = [sys.executable, os.path.join(HERE, "convert_logo.py"), P["source"],
            "--fit", cv["fit"], "--resample", cv["resample"], "--threshold", str(cv["threshold"]),
            "--png", cv["png"], "--out-c", cv["header"], "--name", cv["name"]]
    for flag in ("dither", "crop", "invert"):
        if cv[flag]:
            conv.append("--" + flag)
    run(conv)
    clean_bytes = frame_bytes_from_header(os.path.join(ROOT, cv["header"]))
    assert len(clean_bytes) == g.FRAME_SIZE, len(clean_bytes)
    clean = g.load_clean(os.path.join(ROOT, cv["png"]))

    # 2. glitch pools, same seeds the simulator uses
    if gl["style"] == "line":
        pool = g.LineGenerator(clean, gl["severity"], gl["seed"], flash=gl["flash"],
                               direction=gl["direction"]).sequence(gl["pool_size"])
    else:
        pool = g.GlitchGenerator(clean, gl["severity"], gl["seed"]).sequence(gl["pool_size"])
    rng = random.Random(di["seed"])
    dirty = [s.make_dirty(clean, clean, rng) for _ in range(di["count"])]

    # 3. write logo_frames.h
    header = [
        "// Generated by tools/build_logo.py from tools/logo_params.json -- do not edit by hand.",
        "#pragma once",
        "",
        "#define logo_glitch_count %d" % len(pool),
        "#define logo_glitch_dirty_count %d" % len(dirty),
        "",
    ]
    header += emit_single("static const char PROGMEM %s[frame_size] = {" % arr["clean"], clean_bytes)
    header += [""]
    header += emit_array("static const char PROGMEM %s[logo_glitch_count][frame_size] = {" % arr["glitch"], pool)
    header += [""]
    header += emit_array("static const char PROGMEM %s[logo_glitch_dirty_count][frame_size] = {" % arr["glitch_dirty"], dirty)
    open(frames_h, "w").write("\n".join(header) + "\n")
    print("wrote", P["frames_h"])

    # 3b. oled.c: include the header in place of the logo arrays and their counts
    lines = open(oled).read().split("\n")
    inc = INCLUDE_LINE % P["frames_h"]
    if inc not in lines:
        backup = os.path.join(ROOT, P["backup_dir"], "oled_backup_%s.c" % time.strftime("%Y%m%d_%H%M%S"))
        shutil.copy(oled, backup)
        print("oled.c backup at", os.path.relpath(backup, ROOT))
        lines = replace_block(lines, "static const char PROGMEM %s[frame_size]" % arr["clean"], [inc])
        lines = replace_block(lines, "static const char PROGMEM %s[logo_glitch_count]" % arr["glitch"], [])
        lines = replace_block(lines, "static const char PROGMEM %s[logo_glitch_dirty_count]" % arr["glitch_dirty"], [])
        lines = [l for l in lines if not l.startswith("#define logo_glitch_count")
                 and not l.startswith("#define logo_glitch_dirty_count")]
        open(oled, "w").write("\n".join(lines))
        print("oled.c now includes", P["frames_h"])
    else:
        print("oled.c already includes", P["frames_h"])

    # 4. read back from the header and check against the generation
    src = open(frames_h).read()
    got_clean = read_array(src, arr["clean"])
    got_pool = read_array(src, arr["glitch"])
    got_dirty = read_array(src, arr["glitch_dirty"])
    want_pool = [b for f in pool for b in f]
    want_dirty = [b for f in dirty for b in f]
    ok = got_clean == clean_bytes and got_pool == want_pool and got_dirty == want_dirty
    print("check clean:", got_clean == clean_bytes,
          "glitch:", got_pool == want_pool, "dirty:", got_dirty == want_dirty)
    if not ok:
        sys.exit("readback mismatch: %s is not what the parameters produce" % P["frames_h"])

    # 5. simulation
    if not args.no_sim:
        run([sys.executable, os.path.join(HERE, "simulate_firmware.py"), cv["png"],
             "--style", gl["style"], "--direction", gl["direction"],
             "--severity", str(gl["severity"]), "--pool-size", str(gl["pool_size"]),
             "--gen-seed", str(gl["seed"]), "--sim-seed", str(sm["sim_seed"]),
             "--dirty-count", str(di["count"]), "--sim-seconds", str(sm["sim_seconds"]),
             "--tick-ms", str(sm["tick_ms"]), "--scale", str(sm["scale"]),
             "--gif", sm["gif"]] + ([] if gl["flash"] else ["--no-flash"]))


if __name__ == "__main__":
    main()
